/**
 * ひらがな・全角カタカナを半角カタカナに変換する
 * @param {string} str - 入力文字列 (ひらがな、または全角カタカナ)
 * @returns {string} - 半角カタカナに変換された文字列
 */
export function toHalfWidthKatakana(str) {
  if (!str) return '';
  
  // 1. ひらがなを全角カタカナに変換
  const fullKatakana = str.replace(/[\u3041-\u3096]/g, match => 
    String.fromCharCode(match.charCodeAt(0) + 0x60)
  );
  
  // 2. 全角カタカナを半角カタカナに変換
  let result = '';
  for(let i = 0; i < fullKatakana.length; i++) {
    result += KANA_MAP[fullKatakana[i]] || fullKatakana[i];
  }
  
  return result;
}
